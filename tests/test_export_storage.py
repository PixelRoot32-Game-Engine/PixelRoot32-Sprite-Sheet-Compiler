ARRAY_LINE = re.compile(r"^(static const|inline constexpr) \w+\s+(\w+)\[", re.MULTILINE)


def _make_image(colors):
    img = Image.new("RGBA", (8, 2), (0, 0, 0, 0))
    for x in range(8):
        color = colors[x % len(colors)]
        if color is not None:
            img.putpixel((x, 0), color + (255,))
            img.putpixel((7 - x, 1), color + (255,))
    return img


def export_header(palette, mode, prefix, out_dir):
    """Exports the test image and returns the header text exactly as written."""
    out_path = Path(out_dir) / f"{palette}_{mode}_{prefix.strip() or 'none'}.h"
    options = CompilationOptions(8, 2, 0, 0, mode, str(out_path), prefix)
    assert compile_sprite_sheet(_make_image(PALETTES[palette]), [SpriteDefinition(0, 0, 1, 1, 0)], options)
    return out_path.read_bytes().decode("utf-8")


def _with_pragma(text, mode):
    marker = f"// Mode: {mode}\n\n"
    assert text.startswith("// Generated by PixelRoot32 Sprite Compiler\n")
    return text.replace(marker, marker + "#pragma once\n\n", 1)


class ExportStorageTests(unittest.TestCase):
    def setUp(self):
        self._tmp = tempfile.TemporaryDirectory()
        self.out_dir = self._tmp.name

    def tearDown(self):
        self._tmp.cleanup()

    def test_unprefixed_output_is_v031_plus_pragma_once(self):
        for (palette, mode), v031 in V031_UNPREFIXED.items():
            with self.subTest(palette=palette, mode=mode):
                text = export_header(palette, mode, "", self.out_dir)
                self.assertEqual(text, _with_pragma(v031, mode))
                self.assertIn("\n#pragma once\n", text)
                self.assertIn("static const", text)
                self.assertNotIn("inline constexpr", text)

    def test_whitespace_prefix_keeps_static_const(self):
        text = export_header("custom", "4bpp", "   ", self.out_dir)
        self.assertIn("#pragma once", text)
        self.assertNotIn("inline constexpr", text)
        self.assertEqual(len(ARRAY_LINE.findall(text)), 2)
        for storage, _ in ARRAY_LINE.findall(text):
            self.assertEqual(storage, "static const")

    def test_prefixed_output_uses_inline_constexpr(self):
        for palette, mode in V031_UNPREFIXED:
            with self.subTest(palette=palette, mode=mode):
                text = export_header(palette, mode, "PLAYER", self.out_dir)
                self.assertIn("\n#pragma once\n", text)
                self.assertNotIn("static const", text)
                arrays = ARRAY_LINE.findall(text)
                self.assertTrue(arrays)
                for storage, name in arrays:
                    self.assertEqual(storage, "inline constexpr")
                    self.assertTrue(name.startswith("PLAYER_"), name)
                # Only the storage keyword and the prefix differ from the unprefixed output.
                normalized = text.replace("inline constexpr", "static const").replace("PLAYER_", "")
                self.assertEqual(normalized, _with_pragma(V031_UNPREFIXED[(palette, mode)], mode))

    def test_prefixed_symbol_names_are_unchanged(self):
        text = export_header("custom", "4bpp", "PLAYER", self.out_dir)
        self.assertIn("inline constexpr Color PLAYER_PALETTE_MAPPING[16] = {\n", text)
        self.assertIn("inline constexpr uint16_t PLAYER_SPRITE_0_4BPP[] = {\n", text)
        text = export_header("custom", "2bpp", "PLAYER", self.out_dir)
        self.assertIn("inline constexpr uint16_t PLAYER_SPRITE_0_2BPP[] = {\n", text)
        text = export_header("custom", "layered", "PLAYER", self.out_dir)
        self.assertIn("inline constexpr uint16_t PLAYER_SPRITE_0_LAYER_0[] = {\n", text)
        self.assertIn("inline constexpr uint16_t PLAYER_SPRITE_0_LAYER_1[] = {\n", text)


STUB = """#pragma once
#include <cstdint>
namespace pixelroot32 { namespace graphics { enum class Color : uint8_t { }; } }
"""

ADDR_TU = """#include "stub.h"
#include "sprites.h"
#include "sprites.h"
const void* {fn}_sprite() {{ return {sprite}; }}
const void* {fn}_palette() {{ return {palette}; }}
"""

MAIN_TU = """#include <cstdio>
const void* a_sprite(); const void* a_palette();
const void* b_sprite(); const void* b_palette();
int main() {
    std::printf("%d %d\\n", a_sprite() == b_sprite(), a_palette() == b_palette());
    return 0;
}
"""


@unittest.skipIf(shutil.which("g++") is None, "g++ not found on PATH")
class ExportCompileTests(unittest.TestCase):
    """Compiles generated headers as C++17 into two translation units."""

    def _build_and_run(self, prefix):
        with tempfile.TemporaryDirectory() as tmp:
            work = Path(tmp)
            header = export_header("custom", "4bpp", prefix, tmp)
            (work / "sprites.h").write_text(header, encoding="utf-8", newline="\n")
            (work / "stub.h").write_text(STUB, encoding="utf-8", newline="\n")
            sprite = f"{prefix}_SPRITE_0_4BPP" if prefix else "SPRITE_0_4BPP"
            palette = f"{prefix}_PALETTE_MAPPING" if prefix else "PALETTE_MAPPING"
            for fn in ("a", "b"):
                (work / f"{fn}.cpp").write_text(
                    ADDR_TU.format(fn=fn, sprite=sprite, palette=palette), encoding="utf-8"
                )
            (work / "main.cpp").write_text(MAIN_TU, encoding="utf-8")
            exe = work / "check.exe"
            build = subprocess.run(
                ["g++", "-std=c++17", "-Wall", "-o", str(exe), "a.cpp", "b.cpp", "main.cpp"],
                cwd=tmp, capture_output=True, text=True,
            )
            self.assertEqual(build.returncode, 0, build.stderr)
            run = subprocess.run([str(exe)], cwd=tmp, capture_output=True, text=True)
            self.assertEqual(run.returncode, 0, run.stderr)
            return run.stdout.strip()

    def test_prefixed_header_has_single_copy_across_translation_units(self):
        self.assertEqual(self._build_and_run("PLAYER"), "1 1")

    def test_unprefixed_header_still_compiles(self):
        # Each translation unit keeps its own internal-linkage copy (documented behaviour).
        self.assertEqual(self._build_and_run(""), "0 0")


if __name__ == "__main__":
    unittest.main()
